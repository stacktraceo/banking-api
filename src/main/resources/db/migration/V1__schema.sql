CREATE FUNCTION preserve_initial_deposit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.initial_balance <> OLD.initial_balance OR NEW.user_id <> OLD.user_id THEN
        RAISE EXCEPTION 'Initial deposit and account owner are immutable' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER account_immutable BEFORE UPDATE ON account
    FOR EACH ROW EXECUTE FUNCTION preserve_initial_deposit();

-- Serialize contact changes even for callers using DAO/SQL directly.
CREATE FUNCTION lock_contact_owner() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM id FROM app_user WHERE id=NEW.user_id FOR UPDATE;
    ELSIF TG_OP = 'DELETE' THEN
        PERFORM id FROM app_user WHERE id=OLD.user_id FOR UPDATE;
    ELSE
        PERFORM id FROM app_user WHERE id IN (OLD.user_id, NEW.user_id) ORDER BY id FOR UPDATE;
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
CREATE TRIGGER email_owner_lock BEFORE INSERT OR UPDATE OR DELETE ON email_data
    FOR EACH ROW EXECUTE FUNCTION lock_contact_owner();
CREATE TRIGGER phone_owner_lock BEFORE INSERT OR UPDATE OR DELETE ON phone_data
    FOR EACH ROW EXECUTE FUNCTION lock_contact_owner();

-- Deferred checks allow migrations/tests to create a complete user in one transaction.
CREATE FUNCTION check_complete_user(target BIGINT) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM app_user WHERE id=target) AND (
        NOT EXISTS (SELECT 1 FROM account WHERE user_id=target) OR
        NOT EXISTS (SELECT 1 FROM email_data WHERE user_id=target) OR
        NOT EXISTS (SELECT 1 FROM phone_data WHERE user_id=target)
    ) THEN
        RAISE EXCEPTION 'User requires an account, email and phone' USING ERRCODE='23514';
    END IF;
END $$;
CREATE FUNCTION enforce_complete_user() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME='app_user' THEN
        PERFORM check_complete_user(NEW.id);
    ELSE
        IF TG_OP <> 'INSERT' THEN PERFORM check_complete_user(OLD.user_id); END IF;
        IF TG_OP <> 'DELETE' THEN PERFORM check_complete_user(NEW.user_id); END IF;
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER user_complete AFTER INSERT ON app_user
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_complete_user();
CREATE CONSTRAINT TRIGGER email_complete AFTER INSERT OR UPDATE OR DELETE ON email_data
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_complete_user();
CREATE CONSTRAINT TRIGGER phone_complete AFTER INSERT OR UPDATE OR DELETE ON phone_data
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_complete_user();
CREATE CONSTRAINT TRIGGER account_complete AFTER INSERT OR UPDATE OR DELETE ON account
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_complete_user();
