CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(500) NOT NULL CHECK (length(trim(name)) > 0),
    date_of_birth DATE NOT NULL,
    password VARCHAR(500) NOT NULL CHECK (length(password) >= 8)
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_user(id),
    balance NUMERIC(19,2) NOT NULL CHECK (balance >= 0),
    initial_balance NUMERIC(19,2) NOT NULL CHECK (initial_balance >= 0)
);
CREATE TABLE email_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    email VARCHAR(200) NOT NULL UNIQUE CHECK (email = lower(trim(email)) AND position('@' in email) > 1)
);
CREATE INDEX email_data_user_idx ON email_data(user_id);
CREATE TABLE phone_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    phone VARCHAR(13) NOT NULL UNIQUE CHECK (phone ~ '^[0-9]{11,13}$')
);
CREATE INDEX phone_data_user_idx ON phone_data(user_id);
CREATE INDEX app_user_birth_idx ON app_user(date_of_birth);
CREATE INDEX app_user_name_idx ON app_user(name varchar_pattern_ops);

CREATE TABLE money_transfer (
    id UUID PRIMARY KEY,
    idempotency_key UUID NOT NULL,
    from_user_id BIGINT NOT NULL REFERENCES app_user(id),
    to_user_id BIGINT NOT NULL REFERENCES app_user(id),
    value NUMERIC(19,2) NOT NULL CHECK (value > 0),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (from_user_id, idempotency_key),
    CHECK (from_user_id <> to_user_id)
);
CREATE TABLE interest_state (
    id INTEGER PRIMARY KEY CHECK (id=1),
    last_applied_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
